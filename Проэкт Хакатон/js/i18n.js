window.currentLang = 'ru';

function setLanguage(lang) {
  if (!translations[lang]) return;
  window.currentLang = lang;
  try {
    localStorage.setItem('packshift_lang', lang);
  } catch(e) {}

  document.documentElement.lang = (lang === 'md') ? 'ro' : lang;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  if (typeof window.updateCalculations === 'function') {
    window.updateCalculations();
  }
}

function initLanguageSwitcher() {
  let savedLang = 'ru';
  try {
    savedLang = localStorage.getItem('packshift_lang') || 'ru';
  } catch(e) {}

  setLanguage(savedLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const targetLang = e.currentTarget.getAttribute('data-lang');
      if (targetLang && translations[targetLang]) {
        setLanguage(targetLang);
      }
    });
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLanguageSwitcher);
} else {
  initLanguageSwitcher();
}
