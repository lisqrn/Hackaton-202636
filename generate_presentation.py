def build_presentation():
    prs = Presentation()
    # 16:9 standard widescreen dimensions
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank_layout = prs.slide_layouts[6] # completely blank layout

    for i in range(1, 9):
        img_path = os.path.join(SLIDE_IMAGES_DIR, f"slide_{i}.png")
        if not os.path.exists(img_path):
            print(f"Warning: {img_path} not found!")
            continue

        slide = prs.slides.add_slide(blank_layout)
        
        # Add full-screen high-res render of the slide
        slide.shapes.add_picture(img_path, Inches(0), Inches(0), width=prs.slide_width, height=prs.slide_height)
        
        # Add speaker notes to slide
        notes_slide = slide.notes_slide
        tf = notes_slide.notes_text_frame
        tf.text = SPEAKER_NOTES[i - 1]
        
        print(f"Slide {i} added with notes.")

    prs.save(OUTPUT_PPTX)
    print(f"Successfully generated pixel-perfect PPTX: {OUTPUT_PPTX}")

if __name__ == "__main__":
    build_presentation()
